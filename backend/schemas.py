from typing import List, Literal, Optional
try:
    from pydantic import BaseModel, Field, field_validator
    _USE_FIELD_VALIDATOR = True
except ImportError:
    from pydantic import BaseModel, Field, validator as field_validator
    _USE_FIELD_VALIDATOR = False


class CrisisInput(BaseModel):
    """Input data describing the crisis scenario.

    Fields match the crisis definition and can be expanded as needed.
    """
    scenario_name: str = Field(..., description="Human‑readable name of the scenario")
    description: str = Field(..., description="Detailed description of the crisis")
    constraints: List[str] = Field(default_factory=list, description="Business or operational constraints")
    objectives: List[str] = Field(default_factory=list, description="Desired outcomes for the response")


class Strategy(BaseModel):
    """A single strategy generated by the AI model.

    The contract requires exactly three strategies with predetermined IDs.
    The AI is responsible for proposing strategies and explaining risks,
    not calculating quantitative simulation outcomes.
    """
    strategy_id: Literal["emergency_sourcing", "wait_for_recovery", "split_procurement"]
    title: str = Field(..., description="Short title of the strategy")
    description: str = Field(..., description="Full description of the approach")
    risk_analysis: Optional[str] = Field(
        default=None,
        description="Qualitative explanation of operational, financial, or timing risks"
    )


class AIResponse(BaseModel):
    """Top‑level response model returned by the Nemotron model.

    It must contain a list of three unique strategies with the required IDs.
    """
    strategies: List[Strategy] = Field(..., min_length=3, max_length=3)

    if _USE_FIELD_VALIDATOR:
        @field_validator("strategies")
        @classmethod
        def check_unique_ids(cls, v: List[Strategy]):
            ids = [s.strategy_id for s in v]
            expected = {"emergency_sourcing", "wait_for_recovery", "split_procurement"}
            if len(ids) != len(set(ids)):
                raise ValueError(f"Duplicate strategy IDs found: {ids}")
            if set(ids) != expected:
                raise ValueError(
                    f"Strategies must contain exactly the IDs {expected}, got {set(ids)}"
                )
            return v
    else:
        from pydantic import validator
        @validator("strategies")
        def check_unique_ids(cls, v: List[Strategy]):
            ids = [s.strategy_id for s in v]
            expected = {"emergency_sourcing", "wait_for_recovery", "split_procurement"}
            if len(ids) != len(set(ids)):
                raise ValueError(f"Duplicate strategy IDs found: {ids}")
            if set(ids) != expected:
                raise ValueError(
                    f"Strategies must contain exactly the IDs {expected}, got {set(ids)}"
                )
            return v

