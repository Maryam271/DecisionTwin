def test_offline_strategy_generation_pipeline(supplier_disruption_crisis, mock_nemotron_strategy_response):
    """Verify end-to-end strategy generation from Member 3's input to verified AIResponse."""
    def mock_post(request: httpx.Request):
        assert request.headers["Authorization"] == "Bearer mock-offline-key"
        sent_body = json.loads(request.content)
        assert sent_body["model"] == "offline-nemotron-model"
        assert "Primary Supplier Disruption" in sent_body["messages"][1]["content"]
        return httpx.Response(200, json=mock_nemotron_strategy_response)

    client = httpx.Client(transport=httpx.MockTransport(mock_post))
    service = AIService(
        api_key="mock-offline-key",
        endpoint="https://mock.api.nebius.local/v1/chat/completions",
        model="offline-nemotron-model",
        client=client,
    )

    ai_response = service.get_strategies(supplier_disruption_crisis)

    assert isinstance(ai_response, AIResponse)
    assert len(ai_response.strategies) == 3
    ids = [s.strategy_id for s in ai_response.strategies]
    assert ids == ["emergency_sourcing", "wait_for_recovery", "split_procurement"]

    for strat in ai_response.strategies:
        assert strat.title
        assert strat.description
        assert strat.risk_analysis


