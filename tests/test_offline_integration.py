def test_offline_ai_briefing_simulation_grounding_and_no_invention(supplier_disruption_crisis, member2_sample_simulation_results):
    """Verify that when AI generates the briefing, it receives exact numbers and prompt enforces no invention."""
    def mock_briefing_post(request: httpx.Request):
        sent_body = json.loads(request.content)
        user_prompt_text = sent_body["messages"][1]["content"]
        system_prompt_text = sent_body["messages"][0]["content"]

        # 1. System prompt strictly forbids hallucinating or inventing numbers
        assert "Never invent, hallucinate, or extrapolate metrics" in system_prompt_text
        assert "Rely ONLY on the supplied simulation results" in user_prompt_text

        # 2. Exact simulation figures from Member 2 are faithfully sent in prompt payload
        assert "-1850000" in user_prompt_text
        assert "-4200000" in user_prompt_text
        assert "-2350000" in user_prompt_text
        assert "92.5" in user_prompt_text

        model_response_text = (
            "Executive Trade-off Analysis:\n"
            "Emergency Sourcing minimizes recovery time to 14 days and preserves 92.5% capacity at -$1.85M. "
            "Wait for Recovery is financially catastrophic with -$4.2M impact and 45 days delay. "
            "Split Procurement offers the optimal balance with 85.0% capacity retained and -$2.35M impact."
        )
        return httpx.Response(200, json={"choices": [{"message": {"content": model_response_text}}]})

    client = httpx.Client(transport=httpx.MockTransport(mock_briefing_post))
    service = AIService(
        api_key="mock-offline-key",
        endpoint="https://mock.api.nebius.local/v1/chat/completions",
        model="offline-nemotron-model",
        client=client,
    )

    ai_briefing = generate_executive_briefing(
        supplier_disruption_crisis,
        member2_sample_simulation_results,
        ai_service=service,
    )

    # Verify returned briefing references only ground-truth outputs
    assert "14 days" in ai_briefing
    assert "92.5%" in ai_briefing
    assert "-$1.85M" in ai_briefing
    assert "-$4.2M" in ai_briefing
    assert "-$2.35M" in ai_briefing


